"""Verify released Ripple processors; adapt file locations, not their algorithms."""

import hashlib
import importlib.util
import json
import pickle
import platform
import sys
from collections import defaultdict
from pathlib import Path
from types import ModuleType
from typing import Any

from benchmarks.sources import PinnedSource


def _module(name: str, path: Path) -> ModuleType:
	spec = importlib.util.spec_from_file_location(name, path)
	assert spec is not None and spec.loader is not None
	result = importlib.util.module_from_spec(spec)
	sys.modules[name] = result
	spec.loader.exec_module(result)
	return result


def verify(checkout: Path, output: Path, *, seed: int = 71) -> dict[str, Any]:
	"""Check every row after inserts, deletes and feature changes on a simple graph.

	Run in a fresh process: upstream imports use the generic ``src`` namespace.
	Only files generated by this command are passed to upstream pickle loaders.
	"""
	if "src" in sys.modules or "__init__" in sys.modules:
		raise RuntimeError("Run Ripple verification in a fresh process to isolate upstream imports")
	pin = PinnedSource.load("ripple")
	output.mkdir(parents=True, exist_ok=False)
	source = pin.snapshot(checkout, output / "source")
	single = source / "src/workloads/w3_gcn_mean/single"
	paths = [source / "src/models/custom_models.py", single / "rc.py", single / "in.py"]
	hashes = {path.relative_to(source).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest() for path in paths}
	sys.path[:0] = [str(single), str(source)]

	import dgl
	import numpy as np
	import torch

	models = _module("ripple_author_models", paths[0])
	recompute = _module("ripple_author_rc", paths[1])
	incremental = _module("ripple_author_incremental", paths[2])
	events = _module("ripple_author_events", source / "src/utils/graphstream.py")
	operations = sys.modules["src.utils.operations"].OperationType
	torch.set_num_threads(1)
	torch.manual_seed(seed)
	count, features, hidden, classes, layers = 16, 4, 8, 3, 2
	nodes = torch.arange(count)
	graph = dgl.graph((nodes.repeat(2), torch.cat(((nodes + 1) % count, (nodes + 3) % count))), num_nodes=count)
	x = torch.randn(count, features) * 0.1
	model = models.CustomGraphConvMean(features, classes, hidden, layers).eval()
	weights = [layer.W.weight.detach().numpy().T.copy() for layer in model.layers]
	logits: dict[int, Any] = {}

	def capture(index):
		def hook(layer, inputs, value):
			logits[index] = value.detach().numpy().copy()

		return hook

	hooks = [layer.register_forward_hook(capture(i + 1)) for i, layer in enumerate(model.layers)]

	def full():
		with torch.inference_mode():
			return model([graph] * layers, x).numpy().copy()

	full()
	data, state = output / "data/shared", output / "state"
	data.mkdir(parents=True)
	state.mkdir()
	outgoing, incoming = defaultdict(set), defaultdict(set)
	for u, v in zip(*(tensor.tolist() for tensor in graph.edges()), strict=True):
		outgoing[u].add(v)
		incoming[v].add(u)
	for name, value in (("adj_list", outgoing), ("in_adj_list", incoming)):
		(data / f"{name}.pkl").write_bytes(pickle.dumps(value))
	(state / "weights.pkl").write_bytes(pickle.dumps(weights))
	for index in range(layers + 1):
		raw = x.numpy().copy() if index == 0 else logits[index]
		embedding = np.maximum(0, raw) if 0 < index < layers else raw
		np.save(state / f"embeddings_l{index}.npy", embedding)
		np.save(state / f"logits_l{index}.npy", raw)

	def initialize(upstream):
		class Config(upstream.Config):
			@property
			def model_root(self):
				return state

			@property
			def embs_root(self):
				return state

		config = Config("shared", 1, layers, hidden, 6, output / "data", 1)
		return upstream.GraphStreamProcessor(config)

	processors = {"Ripple-RC": initialize(recompute), "Ripple-incremental": initialize(incremental)}
	event = events.GraphStreamEvent
	batches = [
		("insert", [event(0, operations.EDGE_ADD, source_id=0, target_id=2)]),
		("delete", [event(1, operations.EDGE_DELETE, source_id=0, target_id=1)]),
		("features", [event(2, operations.NODE_UPDATE, node_id=3, feature=np.full(features, 0.25, dtype=np.float32))]),
		(
			"mixed",
			[
				event(3, operations.EDGE_ADD, source_id=4, target_id=8),
				event(3, operations.EDGE_DELETE, source_id=4, target_id=5),
			],
		),
		(
			"zero-in-degree",
			[
				event(4, operations.EDGE_DELETE, source_id=5, target_id=6),
				event(4, operations.EDGE_DELETE, source_id=3, target_id=6),
			],
		),
		("restore-in-degree", [event(5, operations.EDGE_ADD, source_id=5, target_id=6)]),
		("noop", []),
	]
	fixture_hash = hashlib.sha256()
	for path in sorted([*data.glob("*"), *state.glob("*")]):
		fixture_hash.update(path.relative_to(output).as_posix().encode() + b"\0" + path.read_bytes())
	records = []
	for label, batch in batches:
		for change in batch:
			if change.operation_type == operations.EDGE_ADD:
				graph.add_edges(change.source_id, change.target_id)
			elif change.operation_type == operations.EDGE_DELETE:
				graph.remove_edges(graph.edge_ids(change.source_id, change.target_id))
			else:
				x[change.node_id] = torch.from_numpy(change.feature)
		expected = full()
		for name, processor in processors.items():
			processor.process_batch(batch)
			actual = processor.embeddings[layers]
			np.testing.assert_allclose(actual, expected, atol=1e-6, rtol=1e-5)
			records.append(
				{
					"implementation": name,
					"batch": label,
					"rows_checked": count,
					"max_error": float(np.max(np.abs(actual - expected))),
				}
			)
	for hook in hooks:
		hook.remove()
	if any(hashlib.sha256((source / name).read_bytes()).hexdigest() != value for name, value in hashes.items()):
		raise RuntimeError("An upstream implementation changed during verification")
	report = {
		"schema_version": 1,
		"upstream_repository": pin.repository,
		"upstream_revision": pin.revision,
		"implementation_hashes": hashes,
		"unmodified_algorithm": True,
		"adaptations": ["Config.model_root and Config.embs_root redirect generated fixtures to the output directory"],
		"scope": "synthetic numerical verification only; no performance measurement",
		"workload": "authors GC-mean; directed simple graph; no self loops",
		"operator": {
			"name": "CustomGraphConvMean",
			"math": "author GC-mean",
			"compatible_with_neutronrt_graphsage_mean": False,
		},
		"replay": {
			"stateful_successive_batches": True,
			"checked_every_row_after_each_batch": True,
			"batches": [label for label, _ in batches],
			"performance_replay": False,
			"timing_available": False,
		},
		"model": {"features": features, "hidden": hidden, "classes": classes, "layers": layers},
		"seed": seed,
		"fixture_sha256": fixture_hash.hexdigest(),
		"dependencies": {
			"python": platform.python_version(),
			"torch": torch.__version__,
			"dgl": dgl.__version__,
			"numpy": np.__version__,
		},
		"atol": 1e-6,
		"rtol": 1e-5,
		"valid": True,
		"records": records,
	}
	(output / "verification.json").write_text(json.dumps(report, indent=2) + "\n")
	return report
